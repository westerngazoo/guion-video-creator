"""Regenerates src/py_unicode.rs: Python's `re` and `str` character classes as ranges.

Run with the Python whose Unicode version the export should match:
    python3 tools/gen_tables.py > src/py_unicode.rs
"""
import re, sys, unicodedata
W, S = re.compile(r"\w"), re.compile(r"\s")
def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = pred(chr(cp)) if not (0xD800 <= cp <= 0xDFFF) else False
        if ok and start is None: start = cp
        if not ok and start is not None: out.append((start, cp - 1)); start = None
    if start is not None: out.append((start, 0x10FFFF))
    return out
tabs = {
  "WORD": ranges(lambda c: W.match(c) is not None),
  "SPACE": ranges(lambda c: c.isspace()),
  "LINEBREAK": ranges(lambda c: len(("a" + c + "a").splitlines()) == 2),
}
assert ranges(lambda c: S.match(c) is not None) == tabs["SPACE"]
v = sys.version.split()[0]
print(f"//! Generated by `tools/gen_tables.py` (Python {v}, Unicode {unicodedata.unidata_version}): do not edit by hand.")
print("//! Python's `re` and `str` character classes, as closed ranges of code points:")
print("//! WORD = `\\w`, SPACE = `\\s` and `str.isspace` (`strip`), LINEBREAK = `str.splitlines`.")
for k, r in tabs.items():
    print(f"\npub const {k}: &[(u32, u32)] = &[")
    for i in range(0, len(r), 6):
        print("    " + " ".join(f"(0x{a:X}, 0x{b:X})," for a, b in r[i:i+6]))
    print("];")
